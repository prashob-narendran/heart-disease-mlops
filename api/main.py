"""FastAPI service that serves the heart-disease model.

Endpoints
---------
GET  /              service info and links
GET  /health        liveness/readiness: 200 if the model is loaded, else 503
GET  /model-info    which model is served, its metrics and parameters
POST /predict       score one patient
POST /predict/batch score up to 100 patients
GET  /docs          interactive Swagger UI (generated by FastAPI)

The model (preprocessing + estimator in one sklearn Pipeline) is loaded
once at start-up from MODEL_PATH (default models/model.joblib). Scoring
reuses src.predict.predict_records, so the API, the CLI and CI all return
exactly the same result for the same patient.

Run locally:  uvicorn api.main:app --reload
"""

from __future__ import annotations

import json
import logging
import os
import socket
import time
import uuid
from contextlib import asynccontextmanager
from pathlib import Path

import joblib
from fastapi import APIRouter, FastAPI, HTTPException, Request
from fastapi.responses import JSONResponse

from api.schemas import (
    BatchRequest,
    BatchResponse,
    HealthResponse,
    ModelInfo,
    PatientFeatures,
    PredictionResponse,
)
from src.config import FEATURES, METADATA_FILE, MODEL_FILE
from src.predict import DEFAULT_THRESHOLD, predict_records

API_VERSION = "1.0.0"
# Container/pod name (Kubernetes sets the hostname to the pod name), returned
# in X-Served-By so load balancing across replicas is visible.
INSTANCE = socket.gethostname()

logging.basicConfig(level=os.getenv("LOG_LEVEL", "INFO"),
                    format="%(message)s")
log = logging.getLogger("heart-api")


def _log(event: str, **fields) -> None:
    """One JSON object per line: easy to grep, parse and ship to a log
    system."""
    log.info(json.dumps({"ts": round(time.time(), 3), "event": event,
                         **fields}))


def load_artifacts(app: FastAPI) -> None:
    model_path = Path(os.getenv("MODEL_PATH", MODEL_FILE))
    meta_path = Path(os.getenv("METADATA_PATH", METADATA_FILE))
    app.state.model = None
    app.state.metadata = {}
    try:
        app.state.model = joblib.load(model_path)
        if meta_path.exists():
            app.state.metadata = json.loads(meta_path.read_text())
        _log("model_loaded", path=str(model_path),
             model=app.state.metadata.get("model_name"),
             version=app.state.metadata.get("registered_version"))
    except Exception as exc:  # noqa: BLE001 - serve 503 instead of crashing
        _log("model_load_failed", path=str(model_path), error=str(exc))


@asynccontextmanager
async def lifespan(app: FastAPI):
    app.state.started = time.time()
    load_artifacts(app)
    yield


def create_app() -> FastAPI:
    """Application factory: a fresh app (and model state) per call. The
    module-level `app` below is what uvicorn serves; tests build their own."""
    application = FastAPI(
        title="Heart Disease Risk API",
        version=API_VERSION,
        description=(
            "Predicts the presence of heart disease from 13 clinical "
            "attributes (UCI Heart Disease, Cleveland). Returns the class, "
            "the probability, the confidence and a low/moderate/high risk "
            "band."
        ),
        lifespan=lifespan,
    )
    application.middleware("http")(request_context)
    application.include_router(router)
    return application


async def request_context(request: Request, call_next):
    """Attach a request id and timing to every response and log line."""
    request_id = request.headers.get("X-Request-ID", uuid.uuid4().hex[:12])
    start = time.perf_counter()
    response = await call_next(request)
    elapsed_ms = (time.perf_counter() - start) * 1000
    response.headers["X-Request-ID"] = request_id
    response.headers["X-Process-Time-ms"] = f"{elapsed_ms:.2f}"
    response.headers["X-Served-By"] = INSTANCE
    _log("request", request_id=request_id, method=request.method,
         path=request.url.path, status=response.status_code,
         latency_ms=round(elapsed_ms, 2))
    return response


router = APIRouter()


# ---------------------------------------------------------------- helpers
def _require_model(request: Request):
    model = request.app.state.model
    if model is None:
        raise HTTPException(status_code=503, detail="Model not loaded")
    return model


def _meta(request: Request) -> dict:
    return request.app.state.metadata or {}


def _threshold(request: Request) -> float:
    return float(_meta(request).get("threshold", DEFAULT_THRESHOLD))


# ---------------------------------------------------------------- routes
@router.get("/", include_in_schema=False)
def root(request: Request):
    return {
        "service": "heart-disease-risk-api",
        "version": API_VERSION,
        "model": _meta(request).get("model_name"),
        "instance": INSTANCE,
        "docs": "/docs",
        "endpoints": ["/health", "/model-info", "/predict",
                      "/predict/batch"],
    }


@router.get("/health", response_model=HealthResponse)
def health(request: Request):
    loaded = request.app.state.model is not None
    body = HealthResponse(
        status="ok" if loaded else "unavailable",
        model_loaded=loaded,
        model_name=_meta(request).get("model_name"),
        uptime_seconds=round(time.time() - request.app.state.started, 1),
    )
    # 503 lets Docker/Kubernetes health probes mark the container unhealthy
    return JSONResponse(body.model_dump(), status_code=200 if loaded else 503)


@router.get("/model-info", response_model=ModelInfo)
def model_info(request: Request):
    _require_model(request)
    m = _meta(request)
    return ModelInfo(
        model_name=m.get("model_name", "unknown"),
        model_label=m.get("model_label"),
        registered_version=m.get("registered_version"),
        threshold=_threshold(request),
        features=m.get("features", FEATURES),
        metrics=m.get("metrics", {}),
        best_params=m.get("best_params", {}),
        trained_at_utc=m.get("trained_at_utc"),
        dataset_sha256=m.get("dataset_sha256"),
        git_commit=m.get("git_commit"),
    )


@router.post("/predict", response_model=PredictionResponse)
def predict(patient: PatientFeatures, request: Request):
    model = _require_model(request)
    result = predict_records(model, patient.model_dump(),
                             threshold=_threshold(request))[0]
    m = _meta(request)
    _log("prediction", prediction=result["prediction"],
         probability=result["disease_probability"],
         risk=result["risk_level"])
    return PredictionResponse(**result,
                              model_name=m.get("model_name", "unknown"),
                              model_version=m.get("registered_version"))


@router.post("/predict/batch", response_model=BatchResponse)
def predict_batch(batch: BatchRequest, request: Request):
    model = _require_model(request)
    records = [p.model_dump() for p in batch.patients]
    results = predict_records(model, records, threshold=_threshold(request))
    m = _meta(request)
    _log("batch_prediction", n=len(results),
         positives=sum(r["prediction"] for r in results))
    return BatchResponse(model_name=m.get("model_name", "unknown"),
                         model_version=m.get("registered_version"),
                         n=len(results), results=results)


app = create_app()
